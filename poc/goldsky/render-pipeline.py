#!/usr/bin/env python3
"""Render the Goldsky Turbo pipeline YAML from deployments/<network>.json.

Usage: python3 poc/goldsky/render-pipeline.py [--network testnet] [--start-at <ledger|latest|earliest>] [--webhook-url <url>]

Every deployed offering contract (token + sale) and every single-instance
contract (allowlist, demo asset) goes into the SQL filter. Re-run after each
deploy and `goldsky turbo apply` the result: apply is an upsert that keeps the
pipeline's checkpoint.
"""
import argparse, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]

ap = argparse.ArgumentParser()
ap.add_argument("--network", default="testnet")
ap.add_argument("--start-at", default="latest",
                help="latest | earliest | <ledger sequence>. Goldsky keeps full history, so a ledger number backfills.")
ap.add_argument("--webhook-url", default="https://REPLACE-ME.convex.site/goldsky")
ap.add_argument("--secret-name", default="BWB_WEBHOOK_SECRET")
ap.add_argument("--no-secret", action="store_true", help="omit secret_name (receiver without auth, POC only)")
ap.add_argument("--out", default=None)
args = ap.parse_args()

dep = json.load(open(ROOT / "deployments" / f"{args.network}.json"))

contracts = []  # (label, id)
for offering, parts in dep.get("offerings", {}).items():
    for kind, c in parts.items():
        if c.get("status") == "deployed" and c.get("contract_id"):
            contracts.append((f"{offering} {kind}", c["contract_id"]))
for name, c in dep.get("contracts", {}).items():
    if c.get("contract_id"):
        contracts.append((name, c["contract_id"]))

if not contracts:
    sys.exit("no deployed contracts found")

ids_sql = "\n".join(
    f"        '{cid}'{',' if i < len(contracts) - 1 else ' '}  -- {label}"
    for i, (label, cid) in enumerate(contracts))
secret_line = "" if args.no_secret else f"    secret_name: {args.secret_name}\n"
yaml = f"""# Generated by poc/goldsky/render-pipeline.py from deployments/{args.network}.json. Do not edit by hand.
name: bwb-stellar-events-{args.network}
description: BWB offering contract events on Stellar {args.network}, delivered to Convex
resource_size: xs
sources:
  stellar_events:
    type: dataset
    dataset_name: stellar_{args.network}.events
    version: 1.2.0
    start_at: {args.start_at}
    fetch_parallelism: 2
transforms:
  bwb_events:
    type: sql
    primary_key: id
    sql: |
      SELECT
        id, contract_id, topics, data,
        transaction_hash, transaction_successful, in_successful_contract_call,
        ledger_sequence, ledger_closed_at
      FROM stellar_events
      WHERE type = 'contract'
        AND contract_id IN (
{ids_sql}
        )
sinks:
  convex:
    type: webhook
    from: bwb_events
    url: {args.webhook_url}
{secret_line}    one_row_per_request: false
    batch_size: 100
    batch_flush_interval: 1s
"""
out = pathlib.Path(args.out) if args.out else ROOT / "poc" / "goldsky" / f"pipeline.{args.network}.yaml"
out.write_text(yaml)
shown = out.relative_to(ROOT) if out.is_relative_to(ROOT) else out
print(f"wrote {shown} with {len(contracts)} contracts, start_at={args.start_at}")
